# Rule-Based Chatbot
# This chatbot responds to users using predefined rules and keywords.

print("Welcome to my Chatbot!")
print("You can talk to me. Type 'bye' to exit.")

# Keep the chatbot running until the user wants to exit.
while True:

    # Get input from the user.
    # lower() converts the input to lowercase so that
    # "Hello", "HELLO", and "hello" are treated the same.
    user_input = input("You: ").lower().strip()

    # Check if the user wants to end the conversation.
    if user_input == "bye":
        print("Chatbot: Goodbye! Have a nice day!")
        break

    # Rule 1: Respond to greetings.
    elif user_input in ["hello", "hi", "hey"]:
        print("Chatbot: Hello! How can I help you?")

    # Rule 2: Respond when the user asks how the chatbot is.
    elif "how are you" in user_input:
        print("Chatbot: I am fine, thank you! How are you?")

    # Rule 3: Respond when the user asks for the chatbot's name.
    elif "your name" in user_input or "who are you" in user_input:
        print("Chatbot: I am a simple rule-based chatbot.")

    # Rule 4: Respond to questions about its abilities.
    elif "help" in user_input or "what can you do" in user_input:
        print("Chatbot: I can greet you and answer simple questions.")

    # Rule 5: Respond to thanks.
    elif "thank you" in user_input or "thanks" in user_input:
        print("Chatbot: You're welcome!")

    # Rule 6: Respond to the user asking about the weather.
    elif "weather" in user_input:
        print("Chatbot: I cannot check live weather, but I hope it is nice!")

    # Fallback: Use this when no rule matches the input.
    else:
        print("Chatbot: Sorry, I don't understand that. Please try something else.")